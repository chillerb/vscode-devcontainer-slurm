import * as path from 'path';
import { PREFIX, slug } from '../naming';
import { shellQuote } from '../shell';
import { ConnectionInfo, ConnectionStrategy, JobContext, LocalSshFiles, SessionFile } from './types';

/**
 * The job runs the compute node's sshd as the user on a free high port. Every session is forced into the
 * container (`enter.sh`), and VS Code connects with `ProxyJump <login node>`.
 */
export const sshdStrategy: ConnectionStrategy = {
	type: 'sshd',

	sessionFiles(ctx: JobContext): Record<string, SessionFile> {
		return {
			'sshd_config': { content: sshdConfig(ctx) },
			'enter.sh': { content: enterScript(ctx), executable: true },
		};
	},

	jobFragment(ctx: JobContext): string {
		return `sshd_bin=${shellQuote(ctx.config.connection.sshdPath)}
sshd_pid=
for attempt in $(seq 1 20); do
	port=$((20000 + RANDOM % 30000))
	if (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; then
		continue
	fi
	"$sshd_bin" -D -e -f "$sdir/sshd_config" -p "$port" &
	sshd_pid=$!
	sleep 2
	if kill -0 "$sshd_pid" 2>/dev/null; then
		break
	fi
	sshd_pid=
done
if [ -z "$sshd_pid" ]; then
	log "could not start $sshd_bin"
	exit 1
fi
log "sshd listening on port $port"
publish_connection "port=$port"
wait "$sshd_pid"`;
	},

	hostOptions(cluster: string, info: ConnectionInfo, files: LocalSshFiles): Record<string, string> {
		return {
			HostName: info.node,
			Port: info.values['port'],
			User: info.user,
			ProxyJump: cluster,
			IdentityFile: files.identityFile,
			IdentitiesOnly: 'yes',
			HostKeyAlias: hostKeyAlias(cluster),
			UserKnownHostsFile: files.knownHostsFile,
			StrictHostKeyChecking: 'yes',
		};
	},
};

/** All containers on one cluster share the same sshd host key, pinned under this name. */
export function hostKeyAlias(cluster: string): string {
	return `${PREFIX}-${slug(cluster)}`;
}

function sshdConfig(ctx: JobContext): string {
	return `# Generated by Slurm Dev Container. sshd runs unprivileged inside the Slurm job.
HostKey "${ctx.baseDir}/ssh/host_ed25519"
AuthorizedKeysFile "${ctx.baseDir}/ssh/authorized_keys"
PidFile none
UsePAM no
StrictModes no
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
AllowTcpForwarding yes
X11Forwarding no
PermitTTY yes
PrintMotd no
ForceCommand "${ctx.sessionDir}/enter.sh"
`;
}

function enterScript(ctx: JobContext): string {
	const { config } = ctx;
	const envPrefix = path.posix.basename(config.apptainer.binary) === 'singularity' ? 'SINGULARITYENV_' : 'APPTAINERENV_';
	const env = { ...config.containerEnv, ...config.remoteEnv };
	const exports = Object.entries(env).map(([k, v]) => `export ${envPrefix}${k}=${shellQuote(v)}`);
	return `#!/bin/bash
# Generated by Slurm Dev Container. Runs every SSH session inside the dev container.
sdir=${shellQuote(ctx.sessionDir)}
job=$(sed -n 's/^job=//p' "$sdir/connection" 2>/dev/null)
apptainer=$(sed -n 's/^apptainer=//p' "$sdir/connection" 2>/dev/null)
if [ -z "$job" ] || [ -z "$apptainer" ]; then
	echo "slurm-devcontainer: the container is not running" >&2
	exit 1
fi
${exports.join('\n')}
export ${envPrefix}SLURM_DEVCONTAINER_JOB_ID="$job"
exec "$apptainer" exec --pwd ${shellQuote(config.workspaceFolder)} "instance://${PREFIX}-$job" /bin/sh -c '
if command -v bash >/dev/null 2>&1; then sh=bash; else sh=sh; fi
if [ -n "$1" ]; then exec "$sh" -c "$1"; else exec "$sh" -l; fi' sh "\${SSH_ORIGINAL_COMMAND:-}"
`;
}
